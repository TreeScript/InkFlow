from models.research import ResearchData


def build_content_plan_prompt(topic: str, research_data: ResearchData) -> str:
    research_context = research_data.model_dump_json(
        indent = 2,
        exclude= {"sources"}
    )
    
    return f"""

    당신은 네이버 블로그 콘텐츠의 편집 기획자입니다.

    아직 본문을 작성하지 마세요.

    사용자의 주제와 조사 자료를 분석해서
    어떤 구조로 글을 작성해야 가장 유익하고 자연스러운지
    콘텐츠 기획안을 먼저 작성해주세요.

    [사용자 주제]
    {topic}

    [조사 자료]
    {research_context}


    [기획 원칙]

    - 조사 자료의 정보량을 충분히 활용할 수 있도록 구성해주세요.
    - 단순한 정보 나열형 목차를 만들지 마세요.
    - 독자가 주제를 자연스럽게 이해할 수 있는 흐름을 설계해주세요.
    - 중요한 역사적 배경, 원인, 변화 과정, 현재 상황 등이 있다면 생략하지 마세요.
    - timeline이 중요한 주제라면 시간의 흐름을 고려해주세요.
    - 의미 있는 statistics가 있다면 적절한 섹션에서 활용할 수 있도록 계획해주세요.
    - 같은 내용을 여러 섹션에서 반복하지 마세요.


    [네이버 블로그 관점]

    보고서의 목차처럼 딱딱한 구조는 피해주세요.

    예:
    잘못된 예
    1. 개요
    2. 역사
    3. 특징
    4. 결론

    보다는

    - 여의도는 원래 어떤 곳이었을까?
    - 비행장에서 서울의 중심지로
    - 국회의사당이 여의도로 온 이유
    - 금융의 중심지가 된 과정
    - 지금의 여의도는 어떻게 달라졌을까?

    처럼 독자가 계속 읽고 싶어지는 흐름을 구성해주세요.


    [글의 깊이]

    조사 자료가 충분하고 주제 자체가 역사, 경제, 기술, 시사처럼
    설명이 필요한 주제라면 depth를 deep으로 설정해주세요.

    간단한 생활정보라면 standard 또는 light가 가능합니다.

    deep인 경우 충분한 섹션과 핵심 내용을 구성해주세요.


    [중요]

    - 사용자가 실제로 하지 않은 경험을 기획하지 마세요.
    - 조사 자료에 없는 사실을 새롭게 만들지 마세요.
    - 아직 실제 글은 작성하지 마세요.

    최종 결과는 ContentPlan 구조에 맞게 생성해주세요.

""".strip()