def build_research_prompt(topic: str) -> str:
    return f"""
        다음 주제에 대해 블로그 콘텐츠 제작에 사용할 자료를 웹에서 조사해주세요.

        주제:
        {topic}

        목표:
        단순한 요약문을 만드는 것이 아니라,
        이후 콘텐츠 작성 단계에서 깊이 있고 신뢰도 높은 글을 만들 수 있도록
        구체적인 사실과 배경 정보를 충분히 확보하는 것입니다.

        조사 원칙:
        - 최신성이 중요한 주제는 최신 자료를 우선해주세요.
        - 공식 기관, 공공기관, 주요 언론사, 기업 공식 자료, 전문기관 등을 우선해주세요.
        - 중요한 사실은 가능한 경우 여러 출처를 비교해주세요.
        - 확인되지 않은 정보는 사실처럼 작성하지 마세요.
        - 구체적인 연도, 날짜, 사건, 인물, 변화 과정이 있다면 조사해주세요.
        - 의미 있는 수치나 통계가 있다면 조사해주세요.
        - 사실과 해석을 구분해주세요.
        - 블로그 문체로 작성하지 마세요.
        - 감성적인 표현이나 홍보 문구를 사용하지 마세요.

        key_facts:
        - 독자가 주제를 이해하는 데 중요한 사실을 충분히 수집해주세요.
        - 단순한 한 줄 요약이 아니라 배경 설명도 함께 작성해주세요.

        timeline:
        - 역사, 사건의 변화 과정, 정책 변화 등 시간 순서가 의미 있는 주제라면 작성해주세요.
        - 시간 순서가 의미 없는 주제라면 빈 배열로 두어도 됩니다.

        statistics:
        - 실제로 의미 있는 수치가 있을 때만 포함해주세요.
        - 정확한 수치를 확인할 수 없다면 임의로 생성하지 마세요.

        최종 결과는 지정된 ResearchData 구조에 맞게 생성해주세요.
""".strip()